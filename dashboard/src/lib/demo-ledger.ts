export function getBalanceSeed(period: string): BalanceSeed {
  const row = balanceSeeds.find((r) => r.period === period);
  if (!row) throw new Error(`Kein Demoabschluss für ${period} vorhanden.`);
  return row;
}
export function balanceTotals(row: BalanceSeed) {
  const currentAssets = row.cash + row.receivables + row.inventory + row.otherCurrentAssets;
  const noncurrentAssets = row.intangibles + row.tangibleAssets + row.financialAssets;
  const equity = row.shareCapital + row.capitalReserves + row.retainedEarnings + row.ytdNetIncome;
  const currentLiabilities =
    row.shortDebt +
    row.payables +
    row.shortProvisions +
    row.taxPayable +
    row.otherCurrentLiabilities;
  const longLiabilities = row.longDebt + row.longProvisions;
  return {
    currentAssets,
    noncurrentAssets,
    assets: currentAssets + noncurrentAssets,
    equity,
    currentLiabilities,
    longLiabilities,
    liabilities: equity + currentLiabilities + longLiabilities,
  };
}
